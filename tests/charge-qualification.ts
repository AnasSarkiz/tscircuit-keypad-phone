import assert from 'node:assert/strict'
import {ChargeQualification} from '../firmware/charge-qualification'
import {unreleasedEvidence,type Evidence,type PowerInputs} from '../firmware/power-policy'
const e:Evidence={lteOnlyVerifiedAcrossReset:true,carrierVoiceVerified:true,powerPathValidated:true,thermalAttachmentValidated:true,usbInputValidated:true}
const i:PowerInputs={source:'3A',usbRailGood:true,regnStable:true,temperatureColdOK:true,temperatureHotOK:true,sensorConnected:true,temperatureC:25,requestCharge:true,requestModem:false,requestBacklight:false,boostRailV:0}
const q=new ChargeQualification()
const sample=(t:number,evidence:Evidence,inputs:PowerInputs)=>q.update(t,evidence,inputs,t)
assert.deepEqual([0,100,200,250].map(t=>sample(t,e,i)),[false,false,false,true])
assert.equal(sample(300,e,{...i,source:'1.5A'}),false)
assert.deepEqual([350,450,550,600].map(t=>sample(t,e,i)),[false,false,false,true])
assert.equal(sample(701,e,i),false,'stale sample must disable')
assert.equal(sample(700,e,i),false,'backwards time must disable')
assert.equal(sample(NaN,e,i),false)
q.reset();for(const t of [0,100,200,300,400])assert.equal(sample(t,unreleasedEvidence,i),false)
q.reset();for(const t of [0,100,200,300])sample(t,e,i)
assert.equal(sample(350,e,{...i,temperatureHotOK:false}),false)
q.reset();assert.equal(sample(10000,e,i),false,'reset never preserves qualification')
q.reset();for(const t of [0,100,200,250])sample(t,e,i)
assert.equal(q.checkFresh(350),true,'100 ms boundary remains fresh')
assert.equal(q.checkFresh(351),false,'watchdog removes charge request without another sensor sample')
assert.deepEqual([400,500,600,700,750].map(t=>sample(t,e,i)),[false,false,false,false,true],'stale data requires a fresh full dwell')
assert.equal(q.checkFresh(749),false,'backwards watchdog time disables charging')
assert.deepEqual([800,900,1000,1050].map(t=>sample(t,e,i)),[false,false,false,false],'clock fault latches until reset')
q.reset();for(const t of [0,100,200,250])sample(t,e,i)
assert.equal(sample(250,e,i),false,'duplicate sample timestamps latch clock fault')
assert.deepEqual([300,400,500,550].map(t=>sample(t,e,i)),[false,false,false,false])
q.reset();for(const t of [0,100,200,250])sample(t,e,i)
assert.equal(q.checkFresh(NaN),false,'invalid watchdog clock disables charging')
assert.equal(sample(300,e,i),false,'invalid clock requires reset')

q.reset();for(const t of [0,100,200,250])sample(t,e,i)
assert.equal(q.update(300,e,i,250),false,'reusing the same acquisition cannot refresh a cached sample')
assert.equal(sample(350,e,i),false,'duplicate acquisition fault remains latched')
q.reset();assert.equal(q.update(100,e,i,101),false,'future acquisition timestamp is rejected')
assert.equal(sample(200,e,i),false,'future timestamp fault remains latched')
q.reset();assert.equal(q.update(100,e,i,0),false,'100 ms old sample can begin qualification only')
assert.equal(q.checkFresh(101),false,'101 ms old sample cannot remain enabled')
q.reset();assert.equal(q.update(200,e,i,99),false,'sample older than 100 ms cannot qualify')
q.reset();sample(100,e,i);assert.equal(q.update(200,e,i,99),false,'out-of-order acquisition faults')
console.log('PASS: charge qualification dwell, stale samples, resets, source downgrade and thermal fault')
