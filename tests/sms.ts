import assert from 'node:assert/strict'
import {SmsTransaction} from '../firmware/sms-transaction'
const t=new SmsTransaction()
assert.deepEqual(t.start('+12025550123','Test 1',0),['AT+CMGF=1\r'])
assert.deepEqual(t.line('RING',1),[])
assert.deepEqual(t.line('OK',1),['AT+CSCS="GSM"\r'])
assert.deepEqual(t.line('OK',2),['AT+CMGS="+12025550123"\r'])
assert.throws(()=>t.start('123','busy',3),/busy/)
assert.deepEqual(t.prompt(4),['Test 1\x1a'])
t.line('OK',5);assert.equal(t.state,'result')
t.line('+CMGS: 4',6);t.line('OK',7);assert.equal(t.state,'sent')
for(const [n,b] of [['123\rATH','x'],['123','x\x1a'],['123','A'.repeat(161)],['123','€'],['123','hello\nworld']])assert.throws(()=>t.start(n,b,8),/unsupported/)
t.start('123','Timeout',8);t.line('OK',9);t.line('OK',10);assert.deepEqual(t.tick(5011),['\x1b']);assert.equal(t.state,'failed')
t.start('123','No retry',5012);t.line('OK',5013);t.line('OK',5014);t.prompt(5015);assert.deepEqual(t.tick(125016),[]);assert.equal(t.state,'unknown')
t.start('123','Rejected',125017);t.line('+CMS ERROR: 500',125018);assert.equal(t.state,'failed')
console.log('PASS: SMS staged commands, prompt, acknowledgement order, busy guard, input validation, pre-submit cancel and ambiguous post-submit timeout')

// Expiry is enforced on each inbound event, even if the periodic tick is late.
const late=new SmsTransaction()
late.start('123','Hello',0)
assert.deepEqual(late.line('OK',5000),[]);assert.equal(late.state,'failed')
late.start('123','Hello',5001);late.line('OK',5002);late.line('OK',5003)
assert.deepEqual(late.prompt(10003),['\x1b']);assert.equal(late.state,'failed')
late.start('123','Hello',10004);late.line('OK',10005);late.line('OK',10006);late.prompt(10007)
late.line('+CMGS: 1',10008)
assert.deepEqual(late.line('OK',130007),[]);assert.equal(late.state,'unknown')
// Invalid/backwards clocks fail closed; after Ctrl-Z the outcome is ambiguous.
const clock=new SmsTransaction()
assert.throws(()=>clock.start('123','Hello',NaN),/clock/)
clock.start('123','Hello',100);clock.line('OK',101);clock.line('OK',102)
assert.deepEqual(clock.prompt(101),['\x1b']);assert.equal(clock.state,'failed')
assert.throws(()=>clock.start('123','Hello',99),/clock/)
clock.start('123','Hello',103);clock.line('OK',104);clock.line('OK',105);clock.prompt(106)
assert.deepEqual(clock.line('+CMGS: 3',NaN),[]);assert.equal(clock.state,'unknown')
console.log('PASS: SMS event deadlines and invalid clock fail closed')
