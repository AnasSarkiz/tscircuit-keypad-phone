import assert from 'node:assert/strict'
import { KeyDebouncer,PhoneCore } from '../firmware/phone-core'
const k=new KeyDebouncer()
assert.equal(k.update(['1'],0),null)
assert.equal(k.update(['1'],20),null)
assert.equal(k.update(['1'],31),'1')
assert.equal(k.update(['1'],80),null)
assert.equal(k.update(['1','2'],90),null)
assert.equal(k.update(['1','2'],150),null)
assert.equal(k.update([],160),null)
assert.equal(k.update([],191),null)
assert.equal(k.update(['2'],200),null)
assert.equal(k.update(['2'],231),'2')
// A chord must not become a CALL event when just the other key is released.
const chord=new KeyDebouncer()
assert.equal(chord.update(['CALL','1'],0),null)
assert.equal(chord.update(['CALL'],100),null)
assert.equal(chord.update(['CALL'],500),null)
assert.equal(chord.update([],510),null)
assert.equal(chord.update([],539),null)
assert.equal(chord.update([],541),null)
assert.equal(chord.update(['CALL'],550),null)
assert.equal(chord.update(['CALL'],581),'CALL')
assert.equal(chord.update(['CALL'],900),null)
const p=new PhoneCore()
for(const d of '12345')p.key(d,0)
assert.deepEqual(p.key('CALL',0),['ATD12345;\r'])
assert.deepEqual(p.key('CALL',1),[])
p.feed('OK\r\n');assert.equal(p.state,'dialing')
p.feed('+CL');p.feed('CC: 1,0,0,0,0\r\n');assert.equal(p.state,'active')
p.feed('NO CARR');p.feed('IER\r\n');assert.equal(p.state,'idle')
p.feed('RING\r\n');assert.deepEqual(p.key('CALL',500),['ATA\r'])
assert.deepEqual(p.tick(30500),['ATH\r'])
p.digits='123;AT';assert.deepEqual(p.key('CALL',40000),[])
console.log('PASS: debounce, hold, multikey suppression, dial validation, fragmented URCs, call status, timeout, command injection rejection')
